import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
const require = createRequire(new URL('../mobile/package.json', import.meta.url));
const { PNG } = require('pngjs');
const destination = 'assets/pixel/monsterdex/source-sheets';
const incoming = process.argv[2] ?? 'C:/Users/elroy/Downloads/Monstercards/Monstercards';
const manifest = JSON.parse(readFileSync('assets/pixel/monsterdex/manifest.json', 'utf8'));
mkdirSync(destination, { recursive: true });

function gutters(image, horizontal, from = 0, to = horizontal ? image.width : image.height) {
  const size = horizontal ? image.height : image.width;
  const result = []; let start;
  for (let a = 0; a <= size; a++) {
    let count = 0;
    if (a < size) for (let b = from; b < to; b++) {
      const index = ((horizontal ? a : b) * image.width + (horizontal ? b : a)) * 4;
      if (Math.max(image.data[index], image.data[index + 1], image.data[index + 2]) > 35) count++;
    }
    const dark = a < size && count < (to - from) * .025;
    if (dark && start === undefined) start = a;
    if (!dark && start !== undefined) { if (a - start >= 3) result.push([start, a]); start = undefined; }
  }
  return result;
}
function divisions(gaps, size, cells) {
  const result = [];
  for (let i = 0; i <= cells; i++) {
    const expected = i * size / cells;
    const candidates = gaps.filter(([a,b]) => i === 0 ? a === 0 : i === cells ? b === size : a > 0 && b < size && b-a < size/cells*.35);
    const best = candidates.sort((a,b) => Math.abs((a[0]+a[1])/2-expected)-Math.abs((b[0]+b[1])/2-expected))[0];
    if (!best || Math.abs((best[0]+best[1])/2-expected) > size/cells*.3) throw new Error('Card gutter detection needs review');
    result.push(best);
  }
  return result;
}
const records = [];
for (const sheet of new Set(manifest.entries.map(entry => entry.sourceSheet))) {
  const entries = manifest.entries.filter(entry => entry.sourceSheet === sheet).sort((a,b) => a.sourceCell-b.sourceCell);
  const accepted = sheet.startsWith('source-accepted/');
  const source = (accepted ? `assets/pixel/monsterdex/${sheet}` : join(destination, sheet)).replaceAll('\\', '/');
  if (!accepted && !existsSync(source)) copyFileSync(join(incoming, sheet), source);
  const image = PNG.sync.read(readFileSync(source));
  const rows = entries.length > 1 ? divisions(gutters(image, true), image.height, 3) : null;
  for (const entry of entries) {
    let bounds = [0, 0, image.width, image.height];
    if (rows) {
      const row = Math.floor(entry.sourceCell / 5), column = entry.sourceCell % 5;
      let columns;
      try { columns = divisions(gutters(image, false, rows[row][1], rows[row+1][0]), image.width, 5); }
      catch { columns = divisions(gutters(image, false), image.width, 5); }
      bounds = [Math.max(0, columns[column][1]-2), Math.max(0, rows[row][1]-2), Math.min(image.width, columns[column+1][0]+2), Math.min(image.height, rows[row+1][0]+2)];
    }
    if (bounds[2]-bounds[0] < 150 || bounds[3]-bounds[1] < 200) throw new Error(`Invalid card bounds: ${entry.speciesId}`);
    records.push({ speciesId: entry.speciesId, internalId: entry.internalId, printedName: entry.printedName, source, sheetSize: [image.width,image.height], bounds });
  }
}
records.sort((a,b) => a.internalId-b.internalId);
// No raster files are modified: the native view clips the original atlas at render time.
writeFileSync('assets/pixel/monsterdex/native-card-frames.json', JSON.stringify({ version: 1, records }, null, 2)+'\n');
writeFileSync('mobile/cards.ts', `// Generated by scripts/build-native-cards.mjs. Original art is unchanged.\nimport type { ImageSourcePropType } from 'react-native';\nexport interface CardFrame { source: ImageSourcePropType; sheetSize: [number,number]; bounds: [number,number,number,number]; printedName: string }\nexport const cards: Record<string, CardFrame> = {\n${records.map(r=>`  ${JSON.stringify(r.speciesId)}: {source: require(${JSON.stringify('../'+r.source)}), sheetSize: ${JSON.stringify(r.sheetSize)}, bounds: ${JSON.stringify(r.bounds)}, printedName: ${JSON.stringify(r.printedName)}},`).join('\n')}\n};\n`);
console.log(`Registered ${records.length} complete native card frames from original artwork.`);
