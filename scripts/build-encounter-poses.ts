import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {content} from '../src/content/index.ts';
import {NATIVE_SPRITE_ALIASES} from '../src/content/battle-assets.ts';
const aliases={...NATIVE_SPRITE_ALIASES,ironstork:'steelstork'};
import {readdirSync} from 'node:fs';
const root='assets/pixel/battle/encounter-244';
const rows=readdirSync(root).map(source=>({source,id:aliases[source]??source}));
if(rows.length!==244||new Set(rows.map(r=>r.id)).size!==244||rows.some(r=>!content.species.some(s=>s.id===r.id)))throw Error('Sprite identity coverage mismatch');
const lines=rows.map(({source,id})=>`${JSON.stringify(id)}:{${['idle','attack','hit','defeated'].map(p=>{const path=`${root}/${source}/${p}.png`;if(!existsSync(path))throw Error(path);return `${p}:require(${JSON.stringify('../'+path)})`;}).join(',')}}`);
writeFileSync('mobile/battlePoses.ts',`// Generated by scripts/build-encounter-poses.ts\nimport type {ImageSourcePropType} from 'react-native';\nexport const battlePoses:Record<string,Record<'idle'|'attack'|'hit'|'defeated',ImageSourcePropType>>={${lines.join(',\n')}};\n`);
console.log('244 species × 4 poses validated.');
